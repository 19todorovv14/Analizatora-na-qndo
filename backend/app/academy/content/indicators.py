_NOT_MAGIC = "Индикаторът НЕ е магически buy/sell сигнал — той описва миналото по различен начин."


def _ind_lesson(slug, title, summary, indicator, params, what, measures, calc, uses, mistakes, fails, keywords):
    return lesson(
        slug,
        title,
        summary,
        [_NOT_MAGIC],
        [measures, uses[0] if isinstance(uses, list) else uses, fails[0] if isinstance(fails, list) else fails],
        mistakes=mistakes,
        sections=[
            sec("What it is", what),
            sec("What it measures", measures),
            sec("How it is calculated (conceptually)", *([calc] if isinstance(calc, str) else calc)),
            sec("What traders use it for", *([uses] if isinstance(uses, str) else uses)),
            sec("Common mistakes", *mistakes),
            sec("When it can fail", *([fails] if isinstance(fails, str) else fails)),
        ],
        visual={"type": "indicator", "indicator": indicator, "params": params, "symbol": "BTC/USDT", "timeframe": "1h"},
        keywords=keywords,
        xp=15,
    )


